"""Write eval/cases/CASES.md: every case's report, expected answer, and evidence summaries.

python -m eval.overview
"""

import json

from eval.run import CASES_DIR, load_cases
from eval.scenarios import SCENARIOS

NOTES = {s.id: s.notes for s in SCENARIOS}


def expected(case: dict) -> str:
    service = case["expected"]["root_cause_service"]
    release = case["expected"]["release"]
    if service is None:
        return "no root cause"
    return f"{service}, release {release}" if release else f"{service}, no release"


def main() -> None:
    cases = load_cases()
    lines = [
        "# Evaluation cases",
        "",
        f"{len(cases)} cases captured from the demo stack. Generated by `python -m eval.overview`.",
        "",
        "| Case | Tags | Report | Expected | Evidence |",
        "|---|---|---|---|---|",
    ]
    for c in cases:
        n = len(c["snapshot"]["evidence"])
        lines.append(
            f"| {c['id']} | {', '.join(c['tags'])} | {c['incident']['title']} | "
            f"{expected(c)} | {n} |"
        )
    for c in cases:
        incident = c["incident"]
        scope = ", ".join(incident["services"] or ["all"])
        derived = c["provenance"].get("derived_from")
        lines += [
            "",
            f"## {c['id']}: {incident['title']}",
            "",
            f"- Tags: {', '.join(c['tags'])}",
            f"- Severity: {incident['severity']}; scope: {scope}",
            f"- Description: {incident['description'] or 'none'}",
            f"- Expected: {expected(c)}",
            f"- Injected: {json.dumps(c['scenario']['before_window'] + c['scenario']['onset'])}",
        ]
        if NOTES.get(c["id"]) or derived:
            note = NOTES.get(c["id"]) or ""
            if derived:
                note = f"Copy of {derived} with {c['provenance']['removed']} removed. {note}"
            lines.append(f"- Notes: {note.strip()}")
        if c["snapshot"]["source_errors"]:
            lines.append(f"- Collection errors: {c['snapshot']['source_errors']}")
        lines += ["", "Evidence the model sees:", "", "```text"]
        lines += [f"[{e['source']}] {e['summary']}" for e in c["snapshot"]["evidence"]]
        lines += ["```"]
    (CASES_DIR / "CASES.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {CASES_DIR / 'CASES.md'} ({len(cases)} cases)")


if __name__ == "__main__":
    main()
