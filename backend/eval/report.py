"""Write eval/results/report.md from every variant's results.jsonl.

    python -m eval.report

Scores are recomputed from the per-case grades; nothing is read from summaries.
Intervals are 95% Wilson intervals over status-ok rows.
"""

import json
import math
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
from typing import Any

from eval.grade import METRICS
from eval.run import RESULTS_DIR

LABELS = {
    "correct": "Correct",
    "recall": "Recall (faulty)",
    "specificity": "Specificity (healthy)",
    "release": "Release named",
    "citations": "Citations valid",
    "complete": "Every fault named (two-fault cases)",
}


def wilson(successes: float, n: int) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    z, p = 1.96, successes / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, centre - half), min(1.0, centre + half))


def score(rows: list[dict[str, Any]], metric: str) -> str:
    values = [
        r["grade"][metric] for r in rows if r["status"] == "ok" and r["grade"][metric] is not None
    ]
    if not values:
        return "n/a"
    low, high = wilson(sum(values), len(values))
    return f"{sum(values) / len(values):.0%} ({low:.0%}-{high:.0%}, n={len(values)})"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []


def median(values: list[float]) -> float:
    return values[len(values) // 2]


def mark(value: float | None) -> str:
    return "-" if value is None else ("yes" if value else "NO")


def load(variant_dir: Path) -> tuple[dict, list[dict], list[dict]]:
    info = json.loads((variant_dir / "run.json").read_text())
    return info, read_jsonl(variant_dir / "results.jsonl"), read_jsonl(variant_dir / "errors.jsonl")


def variant_section(name: str, info: dict, rows: list[dict], errors: list[dict]) -> list[str]:
    statuses = defaultdict(int)
    for r in rows:
        statuses[r["status"]] += 1
    cost = sum(Decimal(r["cost_usd"]) for r in rows)
    latencies = sorted(r["latency_s"] for r in rows)
    out_tokens = sorted(r["usage"]["output_tokens"] for r in rows)
    lines = [
        f"## {name}",
        "",
        f"`{info['model']}`, effort `{info['effort']}`, prompt v{info['prompt_version']}, "
        f"{len(rows)} graded rows ({dict(statuses)}), {len(errors)} errors.",
        "",
        "| Metric | Score (95% interval) |",
        "|---|---|",
        *[f"| {LABELS[m]} | {score(rows, m)} |" for m in METRICS],
        "",
    ]
    if rows:
        lines += [
            f"Cost: ${cost:.3f} total, ${cost / len(rows):.4f} per case. "
            f"Latency: median {median(latencies):.1f}s, max {latencies[-1]:.1f}s. "
            f"Output tokens: median {median(out_tokens)}, max {out_tokens[-1]}.",
            "",
            "| Group | Cases | Correct |",
            "|---|---|---|",
        ]
        groups = defaultdict(list)
        for r in rows:
            groups[r["tags"][0]].append(r)
        lines += [
            f"| {g} | {len(rs)} | {score(rs, 'correct')} |" for g, rs in sorted(groups.items())
        ]
        lines += [
            "",
            "| Case | Tags | Expected | Diagnosed | Correct | Release | Citations | Cost | Time |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for r in sorted(rows, key=lambda r: (r["prompt_id"], r["rep"])):
            expected = r["meta"]["expected"]
            root = r["meta"]["root_cause"]
            want = expected["root_cause_service"] or "none"
            if expected["release"]:
                want += f" {expected['release']}"
            got = f"{root['service']} ({root['confidence']})" if root else "none"
            if r["status"] != "ok":
                got = r["status"]
            g = r["grade"] or {}
            lines.append(
                f"| {r['prompt_id']} | {', '.join(r['tags'])} | {want} | {got} | "
                + " | ".join(mark(g.get(m)) for m in ("correct", "release", "citations"))
                + " | "
                f"${Decimal(r['cost_usd']):.3f} | {r['latency_s']:.0f}s |"
            )
    if errors:
        lines += [
            "",
            "Errors:",
            *[f"- {e['prompt_id']} rep{e['rep']}: {e['failure']}" for e in errors],
        ]
    return [*lines, ""]


def main() -> None:
    variants = sorted(
        (p for p in RESULTS_DIR.iterdir() if p.is_dir() and (p / "run.json").exists()),
        key=lambda p: (p.name != "baseline", p.name),
    )
    lines = [
        "# Diagnosis evaluation",
        "",
        "Generated by `python -m eval.report`; traces are in `<variant>/traces/`.",
        "",
    ]
    for variant in variants:
        lines += variant_section(variant.name, *load(variant))
    path = RESULTS_DIR / "report.md"
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
